TEST_RUN_MODES = ("DETECTION_VALIDATION", "ALERT_CHECK", "TELEMETRY_CHECK")


class TestRunCreate(BaseModel):
    # Optional detection that this run is tied to. When omitted, the test is
    # treated as a scenario/telemetry run driven by technique_id only.
    detection_id: Optional[str] = None
    # Optional technique identifier for scenario‑driven runs (e.g. from Explore).
    technique_id: Optional[str] = None
    environment: str = "lab"
    endpoint: Optional[str] = None
    atomic_test_id: Optional[str] = Field(None, max_length=255)
    atomic_test_name: Optional[str] = Field(None, max_length=500)
    atomic_test_number: Optional[int] = Field(None, ge=1, le=999)
    # Hint from the UI about how this run should be interpreted. The runner
    # branches on this value to choose between detection-rule scoring and
    # telemetry-only scoring.
    mode: Optional[str] = "DETECTION_VALIDATION"

    @field_validator("mode")
    @classmethod
    def _validate_mode(cls, value: Optional[str]) -> str:
        normalized = (value or "DETECTION_VALIDATION").upper()
        if normalized not in TEST_RUN_MODES:
            raise ValueError(
                f"mode must be one of {TEST_RUN_MODES}, got {value!r}"
            )
        return normalized

