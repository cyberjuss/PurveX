# Whitelist of Detection fields an AI/user can propose changes to. Deliberately
# narrow: status/lifecycle bookkeeping columns (last_*, created_at) are not
# editable through proposals — they're system-owned. ``criticality`` is
# included so analysts can propose a severity re-tier with justification,
# but RBAC still gates approval via DETECTIONS_CRITICALITY_UPDATE.
PROPOSAL_EDITABLE_FIELDS = {
    "title",
    "description",
    "sigma_rule",
    "siem_type",
    "siem_query",
    "technique_id",
    "status",
    "criticality",
    "owner",
    "notes",
    "lifecycle_stage",
}

PROPOSAL_ACTIONS = {"create", "update", "delete"}
PROPOSAL_PROPOSER_KINDS = {"ai", "user", "git"}
PROPOSAL_STATUSES = {"pending", "approved", "rejected", "applied", "superseded"}


class DetectionProposalCreate(BaseModel):
    """Body for ``POST /proposals``.

    ``target_fields`` is the partial patch the proposer wants to apply.
    For ``action=="update"`` it must be non-empty and keyed by a subset
    of :data:`PROPOSAL_EDITABLE_FIELDS`. For ``action=="delete"`` it is
    ignored. For ``action=="create"`` it must contain the full set of
    non-nullable Detection fields — validated in the router, not here,
    so schema errors and tenant errors return different status codes.
    """

    detection_id: Optional[str] = None
    action: str = "update"
    proposed_by_kind: str = "ai"
    proposed_by_label: str = Field("AI Assistant", max_length=200)
    reason: Optional[str] = Field(None, max_length=4000)
    target_fields: Dict[str, Any] = Field(default_factory=dict)

    @field_validator("action")
    @classmethod
    def _validate_action(cls, v: str) -> str:
        if v not in PROPOSAL_ACTIONS:
            raise ValueError(f"action must be one of {sorted(PROPOSAL_ACTIONS)}")
        return v

    @field_validator("proposed_by_kind")
    @classmethod
    def _validate_kind(cls, v: str) -> str:
        if v not in PROPOSAL_PROPOSER_KINDS:
            raise ValueError(
                f"proposed_by_kind must be one of {sorted(PROPOSAL_PROPOSER_KINDS)}"
            )
        return v

    @field_validator("target_fields")
    @classmethod
    def _validate_fields(cls, v: Dict[str, Any]) -> Dict[str, Any]:
        invalid = [k for k in v if k not in PROPOSAL_EDITABLE_FIELDS]
        if invalid:
            raise ValueError(
                f"fields not allowed in proposals: {sorted(invalid)}"
            )
        return v


