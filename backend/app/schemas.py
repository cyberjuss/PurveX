    auth_secret: Optional[str] = Field(None, max_length=4000)

    @field_validator("provider")
    @classmethod
    def _validate_provider(cls, v: str) -> str:
        if v not in DETECTION_SOURCE_PROVIDERS:
            raise ValueError(
                f"provider must be one of {sorted(DETECTION_SOURCE_PROVIDERS)}"
            )
        return v


