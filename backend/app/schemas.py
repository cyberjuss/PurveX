LIFECYCLE_STAGES = {
    "identify",
    "design",
    "develop",
    "test",
    "deploy",
    "maintain",
}


class DetectionUpdate(BaseModel):
    """Schema for partial detection updates (PATCH)."""
    owner: Optional[str] = Field(None, max_length=255, description="Email of the detection owner")
    notes: Optional[str] = Field(None, max_length=10000, description="Review notes")
    status: Optional[str] = Field(None, max_length=50, description="Lifecycle status")
    criticality: Optional[str] = Field(None, max_length=20, description="Criticality level")
    lifecycle_stage: Optional[str] = Field(
        None,
        max_length=20,
        description=(
            "Detection engineering lifecycle stage. One of: "
            "identify, design, develop, test, deploy, maintain."
        ),
    )

    @field_validator("lifecycle_stage")
    @classmethod
    def _validate_lifecycle_stage(cls, v: Optional[str]) -> Optional[str]:
        if v is None:
            return v
        normalized = v.strip().lower()
        if normalized not in LIFECYCLE_STAGES:
            raise ValueError(
                "lifecycle_stage must be one of: "
                + ", ".join(sorted(LIFECYCLE_STAGES))
            )
        return normalized


