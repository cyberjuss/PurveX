DETECTION_SOURCE_AUTH_TYPES = {"none", "token"}
DETECTION_SOURCE_PROVIDERS = {"git"}


class DetectionSourceBase(BaseModel):
    """Shared fields between create / update / read payloads.

    ``path_glob`` is a git-style double-star glob, evaluated client-side
    (in the sync service) rather than by the server shell, so we don't
    need to shell-escape user input. ``auth_secret`` is plaintext on the
    wire and encrypted at rest.
    """

    name: str = Field(..., min_length=1, max_length=200)
    repo_url: str = Field(..., min_length=1, max_length=1000)
    branch: str = Field("main", max_length=200)
    path_glob: str = Field("detections/**/*.yml", max_length=500)
    auth_type: str = Field("none", max_length=20)
    enabled: bool = True

    @field_validator("repo_url")
    @classmethod
    def _validate_repo_url(cls, v: str) -> str:
        # Lock to http(s) URLs. SSH (``git@…``) is deliberately deferred
        # so we don't need to manage deploy keys in V1.
        lower = v.lower()
        if not (lower.startswith("http://") or lower.startswith("https://")):
            raise ValueError("repo_url must be an http(s) URL")
        return v

    @field_validator("auth_type")
    @classmethod
    def _validate_auth_type(cls, v: str) -> str:
        if v not in DETECTION_SOURCE_AUTH_TYPES:
            raise ValueError(
                f"auth_type must be one of {sorted(DETECTION_SOURCE_AUTH_TYPES)}"
            )
        return v


class DetectionSourceCreate(DetectionSourceBase):
    provider: str = "git"
